//! Tiny 5x7 ASCII bitmap font for dense columnar layouts (week view).
//! Rows are `u8`s holding 5 bits; bit 4 (0x10) is the leftmost column,
//! mirroring `font8x16`'s "left-aligned row bits" convention at a smaller
//! footprint - 7px tall instead of 16, so a narrow week-view column can
//! show roughly twice as many todo lines. Fixed 5px advance + 1px gap.

pub const GLYPH_HEIGHT: usize = 7;
const FIRST_CHAR: u32 = 0x20;
const LAST_CHAR: u32 = 0x7E;
const GLYPH_COUNT: usize = (LAST_CHAR - FIRST_CHAR + 1) as usize;

/// Returns the 7 glyph rows and the advance width. Anything outside the
/// printable ASCII range falls back to a blank space-width glyph.
pub fn glyph5x7(character: char) -> (&'static [u8; GLYPH_HEIGHT], u8) {
    let code = character as u32;
    if !(FIRST_CHAR..=LAST_CHAR).contains(&code) {
        return (&GLYPHS[0], 5);
    }
    let index = (code - FIRST_CHAR) as usize;
    (&GLYPHS[index], 5)
}

